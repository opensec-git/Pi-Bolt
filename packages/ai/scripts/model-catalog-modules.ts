import { readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/*
 * The TypeScript side of the generated catalog, derived from src/providers/data/<provider>.json:
 * - providers/<provider>.catalog.generated.ts: the provider's models as a function that returns them (the data file's text, as an object
 *   literal), and their chat ids and names, so that a process builds only the catalogs it asks for;
 * - providers/<provider>.models.ts: the public X_MODELS, X_IMAGE_MODELS and X_CLASSIFIER_MODELS records, built from it;
 * - models.generated.ts: every provider's records by provider id, each built when first read.
 * The data files are what the generator writes and checks. The catalog modules only repeat them and are not kept in git:
 * whatever writes the data writes them, and every build writes them again (scripts/generate-catalog-modules.ts). The shards and
 * the aggregator depend only on the provider ids and are committed.
 */

export const GENERATED_HEADER = `// This file is auto-generated by catalog/generate.ts
// Do not edit manually - run 'npm run generate-models' to update

`;

const DATA_START = "\t(): typeof values => (";
const DATA_END = "\t),";

function constPrefix(providerId: string): string {
	return providerId.toUpperCase().replace(/[^A-Z0-9]+/g, "_");
}

export const catalogConstName = (providerId: string) => `${constPrefix(providerId)}_MODELS`;
export const imageCatalogConstName = (providerId: string) => `${constPrefix(providerId)}_IMAGE_MODELS`;
export const classifierCatalogConstName = (providerId: string) => `${constPrefix(providerId)}_CLASSIFIER_MODELS`;
export const lazyCatalogConstName = (providerId: string) => `${constPrefix(providerId)}_MODEL_CATALOG`;

type ModelGroups = Record<string, Record<string, { type?: unknown; id?: unknown; name?: unknown }>>;

/** The chat models' ids and names in the order the catalog lists them: id, name, id, name, ... */
export function chatModelNames(groups: ModelGroups): string[] {
	const names: string[] = [];
	for (const models of Object.values(groups)) {
		for (const model of Object.values(models)) {
			if (model.type === "chat") names.push(String(model.id), String(model.name));
		}
	}
	return names;
}

/** Throws for a key an object literal would not read as JSON.parse does (`__proto__` sets the prototype). */
function assertLiteralSafe(value: unknown, path: string): void {
	if (value === null || typeof value !== "object") return;
	for (const [key, entry] of Object.entries(value)) {
		if (key === "__proto__") throw new Error(`${path} has a "__proto__" key, which an object literal cannot hold`);
		assertLiteralSafe(entry, `${path}.${key}`);
	}
}

/** providers/<provider>.catalog.generated.ts for a data file's text. */
export function renderCatalogModule(providerId: string, dataText: string): string {
	const groups = JSON.parse(dataText) as ModelGroups;
	assertLiteralSafe(groups, providerId);
	let output = GENERATED_HEADER;
	output += `import type values from "./data/${providerId}.json";\n`;
	output += `import { lazyModelCatalog } from "../model-catalog.ts";\n\n`;
	output += `/** The models of data/${providerId}.json, built when first asked for. */\n`;
	output += `export const ${lazyCatalogConstName(providerId)} = lazyModelCatalog(\n`;
	output += `\t${JSON.stringify(providerId)},\n`;
	output += `\t() => ${JSON.stringify(chatModelNames(groups))},\n`;
	output += `${DATA_START}\n${dataText.replace(/\n$/, "")}\n${DATA_END}\n);\n`;
	return output;
}

/** The data file text a catalog module holds, or undefined if it is not one. */
export function catalogModuleData(source: string): string | undefined {
	const lines = source.split("\n");
	const start = lines.indexOf(DATA_START);
	const end = lines.indexOf(DATA_END, start + 1);
	if (start < 0 || end < 0) return undefined;
	return lines.slice(start + 1, end).join("\n");
}

/** providers/<provider>.models.ts. */
export function renderShardModule(providerId: string): string {
	const catalog = lazyCatalogConstName(providerId);
	const id = JSON.stringify(providerId);
	let output = GENERATED_HEADER;
	output += `import type values from "./data/${providerId}.json";\n`;
	output += `import type { ChatModelCatalog, ClassifierModelCatalog, ImageModelCatalog } from "../model-catalog.ts";\n`;
	output += `import { ${catalog} } from "./${providerId}.catalog.generated.ts";\n\n`;
	output += `export const ${catalogConstName(providerId)}: ChatModelCatalog<typeof values, ${id}> =\n`;
	output += `\t${catalog}.chat();\n\n`;
	output += `export const ${imageCatalogConstName(providerId)}: ImageModelCatalog<typeof values, ${id}> =\n`;
	output += `\t${catalog}.image();\n\n`;
	output += `export const ${classifierCatalogConstName(providerId)}: ClassifierModelCatalog<typeof values, ${id}> =\n`;
	output += `\t${catalog}.classifier();\n`;
	return output;
}

/** models.generated.ts: each provider's records are read through getters, so a provider's catalog is built when first read. */
export function renderAggregatorModule(providerIds: readonly string[]): string {
	let output = GENERATED_HEADER;
	for (const providerId of providerIds) {
		output += `import type { ${classifierCatalogConstName(providerId)}, ${imageCatalogConstName(providerId)}, ${catalogConstName(providerId)} } from "./providers/${providerId}.models.ts";\n`;
	}
	for (const providerId of providerIds) {
		output += `import { ${lazyCatalogConstName(providerId)} } from "./providers/${providerId}.catalog.generated.ts";\n`;
	}
	const record = (name: string, constName: (providerId: string) => string, method: string) => {
		let text = `export const ${name}: {\n`;
		for (const providerId of providerIds) {
			text += `\treadonly ${JSON.stringify(providerId)}: typeof ${constName(providerId)};\n`;
		}
		text += `} = {\n`;
		for (const providerId of providerIds) {
			text += `\tget ${JSON.stringify(providerId)}() {\n\t\treturn ${lazyCatalogConstName(providerId)}.${method}();\n\t},\n`;
		}
		return `${text}};\n`;
	};
	output += `\n${record("MODELS", catalogConstName, "chat")}`;
	output += `\n${record("IMAGE_MODELS", imageCatalogConstName, "image")}`;
	output += `\n${record("CLASSIFIER_MODELS", classifierCatalogConstName, "classifier")}`;
	output += `\n/** Every provider's catalog, in provider order. */\nexport const MODEL_CATALOGS = [\n`;
	for (const providerId of providerIds) output += `\t${lazyCatalogConstName(providerId)},\n`;
	output += `] as const;\n`;
	return output;
}

/**
 * Writes `text` to `path` unless the file already holds it: an unchanged module keeps its time, so `npm run check` (which
 * writes the catalog modules first) does not make a build look stale to scripts/build-pi.sh.
 */
function writeIfChanged(path: string, text: string): void {
	let current: string | undefined;
	try {
		current = readFileSync(path, "utf8");
	} catch {
		current = undefined;
	}
	if (current !== text) writeFileSync(path, text);
}

/**
 * Writes every provider's catalog module from its data file text (removing those of providers no longer listed), and unless
 * `catalogsOnly` the shards and the aggregator for exactly these providers.
 */
export function writeModelCatalogModules(
	packageRoot: string,
	dataTexts: Readonly<Record<string, string>>,
	options: { catalogsOnly?: boolean } = {},
): void {
	const providersDir = join(packageRoot, "src", "providers");
	const providerIds = Object.keys(dataTexts).sort();
	for (const providerId of providerIds) {
		writeIfChanged(join(providersDir, `${providerId}.catalog.generated.ts`), renderCatalogModule(providerId, dataTexts[providerId]));
	}
	const keep = new Set(providerIds.flatMap((providerId) => [`${providerId}.catalog.generated.ts`, `${providerId}.models.ts`]));
	for (const entry of readdirSync(providersDir)) {
		const generated = entry.endsWith(".catalog.generated.ts") || (!options.catalogsOnly && entry.endsWith(".models.ts"));
		if (generated && !keep.has(entry)) rmSync(join(providersDir, entry));
	}
	if (options.catalogsOnly) return;
	for (const providerId of providerIds) {
		writeIfChanged(join(providersDir, `${providerId}.models.ts`), renderShardModule(providerId));
	}
	writeIfChanged(join(packageRoot, "src", "models.generated.ts"), renderAggregatorModule(providerIds));
}
