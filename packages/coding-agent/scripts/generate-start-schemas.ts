#!/usr/bin/env node
// Writes what a start needs of TypeBox as modules that do not evaluate it (evaluating TypeBox costs every start millions
// of instructions):
// - src/core/tools/tool-schemas.generated.ts: the built-in tools' schemas (tool-schemas.ts) as the objects TypeBox builds,
//   keywords and then TypeBox's markers as non-enumerable properties (src/core/typebox-shaped.ts);
// - src/core/config-checks.generated.ts: TypeBox's compiled checks (the code Compile() generates and evaluates) of the
//   models.json schema and of a keybindings.json value. They need only TypeBox's small `typebox/guard` module.
// Run it after changing a source; `npm run check` and the build run it with --check, which fails on a stale file.
//   npm run generate:start-schemas [-- --check]

import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, posix, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { Build } from "typebox/schema";
import { KeybindingValueSchema } from "../src/core/key-id-schema.ts";
import { modelsConfigSchema } from "../src/core/model-config-schema.generated.ts";
import * as ToolSchemas from "../src/core/tools/tool-schemas.ts";

const packageDirectory = fileURLToPath(new URL("..", import.meta.url));
const toolSchemasModule = "src/core/tools/tool-schemas.generated.ts";
const configChecksModule = "src/core/config-checks.generated.ts";

/** Each generated module, by its path in the package: its content, formatted as `npm run check` leaves it. */
export function renderStartSchemaModules(): ReadonlyMap<string, string> {
	return new Map([
		[toolSchemasModule, renderToolSchemas()],
		[configChecksModule, renderConfigChecks()],
	]);
}

function renderToolSchemas(): string {
	const outDirectory = dirname(toolSchemasModule);
	const seen = new Set<object>();
	// (By name: the order of a module namespace's keys depends on the loader.)
	const exports = Object.entries(ToolSchemas)
		.sort(([a], [b]) => (a < b ? -1 : 1))
		.map(([name, schema]) => `export const ${name}: typeof Source.${name} = ${emitShaped(schema, seen)};`);
	return format(
		[
			"// Generated by scripts/generate-start-schemas.ts from tool-schemas.ts: do not edit (npm run generate:start-schemas).",
			"// The schemas TypeBox builds, as the same objects, built without evaluating TypeBox.",
			"",
			`import { typeBoxShaped } from "${importPath(outDirectory, "src/core/typebox-shaped.ts")}";`,
			`import type * as Source from "${importPath(outDirectory, "src/core/tools/tool-schemas.ts")}";`,
			"",
			...exports,
			"",
		].join("\n"),
		toolSchemasModule,
	);
}

/** A schema value as code that builds the same value: plain data, and typeBoxShaped() where TypeBox added markers. */
function emitShaped(value: unknown, seen: Set<object>): string {
	if (typeof value !== "object" || value === null) return primitive(value);
	// (One object reached twice would become two: no source reuses one.)
	if (seen.has(value)) throw new Error("A schema object is reached twice");
	seen.add(value);
	if (Array.isArray(value)) return `[${value.map((item) => emitShaped(item, seen)).join(", ")}]`;
	if (Object.getPrototypeOf(value) !== Object.prototype || !Object.isExtensible(value)) {
		throw new Error("A schema holds an object that is not plain, or is frozen");
	}
	const keywords: string[] = [];
	const markers: string[] = [];
	for (const key of Reflect.ownKeys(value)) {
		const descriptor = Object.getOwnPropertyDescriptor(value, key);
		if (typeof key !== "string" || !descriptor || !("value" in descriptor)) {
			throw new Error(`Schema property ${String(key)} is not a data property with a string key`);
		}
		if (!descriptor.writable || !descriptor.configurable) throw new Error(`Schema property ${key} is read-only`);
		if (descriptor.enumerable) {
			// typeBoxShaped() adds the markers after the keywords, as TypeBox does.
			if (markers.length > 0) throw new Error(`Schema property ${key} comes after a marker`);
			keywords.push(`${JSON.stringify(key)}: ${emitShaped(descriptor.value, seen)}`);
			continue;
		}
		const marker: unknown = descriptor.value;
		if (typeof marker !== "string" && typeof marker !== "boolean" && marker !== null) {
			throw new Error(`Marker ${key} is not a string, boolean or null`);
		}
		markers.push(`${JSON.stringify(key)}: ${JSON.stringify(marker)}`);
	}
	const object = `{ ${keywords.join(", ")} }`;
	return markers.length === 0 ? object : `typeBoxShaped(${object}, { ${markers.join(", ")} })`;
}

function primitive(value: unknown): string {
	if (typeof value === "number" && !Number.isFinite(value)) throw new Error(`A schema holds ${value}`);
	if (typeof value !== "string" && typeof value !== "number" && typeof value !== "boolean" && value !== null) {
		throw new Error(`A schema holds a ${typeof value}`);
	}
	return JSON.stringify(value);
}

interface ConfigCheck {
	name: string;
	doc: string;
	schema: object;
}

const configChecks: readonly ConfigCheck[] = [
	{
		name: "checkModelsConfig",
		doc: "Whether a models.json document is valid: TypeBox's Value.Check(modelsConfigSchema(), value).",
		schema: modelsConfigSchema(),
	},
	{
		name: "checkKeybindingValue",
		doc: "Whether a keybindings.json value is a key or a list of keys: TypeBox's Value.Check(KeybindingValueSchema, value).",
		schema: KeybindingValueSchema,
	},
];

function renderConfigChecks(): string {
	// TypeBox numbers the variables of its checks (var_0, var_1, ...) with a counter that lives as long as the process: a
	// check built after another one in the same process (this module rendered twice, or after something compiled a
	// schema) would get other numbers. They are numbered again in the order they appear, so the file depends only on the
	// schemas.
	const variables = new Map<string, string>();
	const renumber = (code: string): string =>
		code.replace(/\bvar_\d+\b/g, (variable) => {
			let renamed = variables.get(variable);
			if (renamed === undefined) {
				renamed = `var_${variables.size}`;
				variables.set(variable, renamed);
			}
			return renamed;
		});
	const sections = configChecks.map(({ name, doc, schema }) => {
		const build = Build(schema);
		if (build.UseUnevaluated()) throw new Error(`${name}: the check needs TypeBox's CheckContext`);
		const external = build.External();
		const regexps = external.variables.map((variable) => {
			if (!(variable instanceof RegExp)) throw new Error(`${name}: the check needs a value that is not a RegExp`);
			return `new RegExp(${JSON.stringify(variable.source)}, ${JSON.stringify(variable.flags)})`;
		});
		// TypeBox names the externals array and the functions the same in every build: one scope per check.
		const code = renumber(build.Functions().join(";\n"));
		const used = new Set(code.match(/\b(?:Format|Hashing|CheckContext|context)\b/g));
		if (used.size > 0) throw new Error(`${name}: the check needs ${[...used].join(", ")} from TypeBox`);
		return [
			`/** ${doc} */`,
			`export const ${name}: (value: unknown) => boolean = (() => {`,
			`const ${external.identifier} = [${regexps.join(", ")}];`,
			`${code};`,
			`return (value) => ${renumber(build.Entry())};`,
			"})();",
		].join("\n");
	});
	return format(
		[
			"// @ts-nocheck: TypeBox's generated checks are untyped JavaScript.",
			"// biome-ignore-all lint: TypeBox's generated code, as Compile() generates it.",
			"// Generated by scripts/generate-start-schemas.ts: do not edit (npm run generate:start-schemas).",
			"// TypeBox's compiled checks, the code Compile() would generate and evaluate at run time, so that checking a file",
			"// evaluates neither TypeBox's type builder nor its validator. Value.Check and Compile give the same results.",
			"",
			'import { Guard } from "typebox/guard";',
			"",
			...sections,
			"",
		].join("\n"),
		configChecksModule,
	);
}

// An import specifier, so with "/" on every platform (both arguments are package-relative paths written with "/").
function importPath(fromDirectory: string, to: string): string {
	const path = posix.relative(fromDirectory.replaceAll("\\", "/"), to);
	return path.startsWith(".") ? path : `./${path}`;
}

// As `npm run check` leaves a file (biome check --write: formatted, imports sorted).
function format(source: string, out: string): string {
	const repositoryDirectory = resolve(packageDirectory, "../..");
	// Biome's launcher run by this Node, as scripts/biome-check.mjs runs it: node_modules/.bin/biome is a shell script,
	// which Windows cannot start.
	const biome = createRequire(import.meta.url).resolve("@biomejs/biome/bin/biome");
	const path = resolve(packageDirectory, out);
	const result = spawnSync(process.execPath, [biome, "check", "--write", `--stdin-file-path=${path}`], {
		cwd: repositoryDirectory,
		input: source,
		encoding: "utf-8",
		maxBuffer: 64 * 1024 * 1024,
	});
	if (result.status !== 0) throw new Error(`biome check failed for ${path}:\n${result.stderr}${result.stdout}`);
	return result.stdout;
}

function main(check: boolean): void {
	const stale: string[] = [];
	for (const [out, content] of renderStartSchemaModules()) {
		const path = resolve(packageDirectory, out);
		let current: string | undefined;
		try {
			current = readFileSync(path, "utf-8");
		} catch {
			current = undefined;
		}
		if (current === content) continue;
		if (check) {
			stale.push(`packages/coding-agent/${out}`);
			continue;
		}
		writeFileSync(path, content, "utf-8");
		console.log(`Generated packages/coding-agent/${out}`);
	}
	if (stale.length > 0) {
		console.error(`Stale (run npm run generate:start-schemas in packages/coding-agent):\n  ${stale.join("\n  ")}`);
		process.exit(1);
	}
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	main(process.argv.includes("--check"));
}
