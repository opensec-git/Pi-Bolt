#!/usr/bin/env bash
# Pin the Debian packages in userland/packages.txt to the current trixie arm64 versions: writes userland/debs.lock
# (package version role pool-path sha256). Run on the host; uses the builder's Debian base image.
set -euo pipefail
HERE=$(cd "$(dirname "$0")/.." && pwd)
docker run --rm --platform linux/arm64 -v "$HERE:/engine:ro" \
	"$(sed -n 's/^FROM //p' "$HERE/docker/Dockerfile")" bash -c '
set -euo pipefail
apt-get update -qq
echo "# Generated by scripts/lock-debs.sh from userland/packages.txt (Debian trixie, arm64). Do not edit by hand."
echo "# package version role pool-path sha256 (pool/updates/* is debian-security). @snapshot: snapshot.debian.org fallback time."
echo "@snapshot $(date -u +%Y%m%dT%H%M%SZ)"
grep -v "^#" /engine/userland/packages.txt | while read -r pkg role; do
	[ -n "$pkg" ] || continue
	apt-cache show --no-all-versions "$pkg:arm64" | awk -v p="$pkg" -v r="$role" "
		/^Version: /{v=\$2} /^Filename: /{f=\$2} /^SHA256: /{s=\$2}
		END{print p, v, r, f, s}"
done' >"$HERE/userland/debs.lock.tmp"
mv "$HERE/userland/debs.lock.tmp" "$HERE/userland/debs.lock"
cat "$HERE/userland/debs.lock"
